import io
import csv
from typing import List, Dict, Any, Optional
from backend.app.config import settings
from backend.app.schemas.reports import ReportMetadata

FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")

def sanitize_csv_cell(value: Any) -> str:
    """
    Mitigates spreadsheet formula injection (CSV Injection / CWE-1236).
    If a cell value starts with '=', '+', '-', '@', '\t', or '\r',
    it prepends a single quote "'" to force spreadsheet applications
    (Excel, LibreOffice Calc) to parse the content as a literal string
    rather than an executable formula or command macro.
    """
    if value is None:
        return ""
    s = str(value)
    if s and s[0] in FORMULA_PREFIXES:
        return "'" + s
    return s

class CsvExporter:
    """
    Safe CSV generation engine with anti-formula-injection protection,
    UTF-8 BOM support for Excel, bounded row limits, and metadata headers.
    """

    @classmethod
    def generate_csv(
        cls,
        headers: List[str],
        rows: List[List[Any]],
        metadata: Optional[ReportMetadata] = None,
        include_metadata_header: bool = True
    ) -> bytes:
        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL, lineterminator="\r\n")

        # 1. Optional Metadata Preamble
        if include_metadata_header and metadata:
            writer.writerow([f"# SAMANVAY REPORT: {metadata.report_title}"])
            writer.writerow([f"# Generated At (UTC): {metadata.generated_at.isoformat()}"])
            writer.writerow([f"# Generated By: {metadata.generated_by} (Role: {metadata.user_role}, Bureau: {metadata.user_bureau or 'ALL'})"])
            writer.writerow([f"# Applied Filters: {metadata.selected_filters}"])
            writer.writerow([f"# Record Count: {len(rows)}{' (Truncated to limit)' if metadata.is_truncated else ''}"])
            writer.writerow([])  # Blank separator line

        # 2. Column Headers
        sanitized_headers = [sanitize_csv_cell(h) for h in headers]
        writer.writerow(sanitized_headers)

        # 3. Data Rows with Bounded Limit & Cell Sanitization
        max_rows = settings.MAX_EXPORT_ROWS
        truncated = False
        row_count = 0

        for row in rows:
            if row_count >= max_rows:
                truncated = True
                break
            sanitized_row = [sanitize_csv_cell(cell) for cell in row]
            writer.writerow(sanitized_row)
            row_count += 1

        if truncated and metadata:
            metadata.is_truncated = True

        # Prepend UTF-8 BOM so Microsoft Excel renders international characters properly
        csv_string = output.getvalue()
        bom_utf8_bytes = b"\xef\xbb\xbf" + csv_string.encode("utf-8")
        return bom_utf8_bytes
